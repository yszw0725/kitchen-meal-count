-- 2026-08-14一括移行登録時、residents.entered_onに実際の入所日ではなく
-- 移行作業日(2026-08-14)がそのまま記録されてしまっていた問題の是正。
-- (原因・恒久対応は 20260824090000_resident_entered_on_input.sql を参照)
--
-- get_day_board / get_monthly_summary の在籍判定(entered_on <= 対象日)
-- がこれを参照するため、2026-08-14より前の日付では該当利用者が丸ごと
-- 在籍対象外になり、S2の区分カードが空欄・月次集計が0食になっていた。
--
-- 対象は entered_on = '2026-08-14' の利用者全員。この移行時点で在籍して
-- いた既存利用者であり、実際の入所日はいずれも移行日より前(2026-08-14
-- 当日に本当に入所した利用者はいない)と確認済み。正確な入所日を復元する
-- 手段が無いため、十分に過去のダミー日付(2000-01-01)へ一括で置き換える。
-- 「表示・集計上、過去の日付でも正しく食数計算に含まれる」状態にする
-- ことが目的であり、実入所日の記録を意図するものではない
-- (以後、実入所日が判明した利用者から順にresidents-client.tsx上の
-- 「入所日」欄で個別に訂正していく運用を想定)。
--
-- 一度きりのバックフィルであり、以後再実行を想定しない。

update residents
set entered_on = '2000-01-01'
where entered_on = '2026-08-14';
